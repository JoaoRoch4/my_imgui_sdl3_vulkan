/// Applies the startup flags:
///   --popout=scene,folder,controls   start those panels in their own OS windows
///   --pin                            start with every panel held open
/// Unknown arguments are reported and ignored rather than being fatal — this is a
/// design concept, and refusing to launch over a typo helps nobody.
static void concept_apply_args(int argc, char **argv, ConceptPlayerApp &app)
{
    for (int i = 1; i < argc; ++i) {
        const std::string_view arg{argv[i]};
        if (arg == "--pin") {
            app.pin_all(true);
        } else if (arg.starts_with("--popout=")) {
            std::string_view list = arg.substr(std::string_view("--popout=").size());
            while (!list.empty()) {
                const std::size_t comma = list.find(',');
                const std::string_view name = list.substr(0, comma);
                if (!name.empty() && !app.pop_out_panel(name))
                    SDL_Log("concept_player: unknown panel '%.*s' (want scene|folder|controls)",
                            static_cast<int>(name.size()), name.data());
                if (comma == std::string_view::npos)
                    break;
                list.remove_prefix(comma + 1);
            }
        } else {
            SDL_Log("concept_player: ignoring unknown argument '%.*s'",
                    static_cast<int>(arg.size()), arg.data());
        }
    }
}

int main(int argc, char **argv)
{
    if (!SDL_Init(SDL_INIT_VIDEO)) {
        SDL_Log("SDL_Init: %s", SDL_GetError());
        return 1;
    }

    const float      main_scale = SDL_GetDisplayContentScale(SDL_GetPrimaryDisplay());
    SDL_Window *const window =
        SDL_CreateWindow("Video player — design concept",
                         static_cast<int>(1360 * main_scale), static_cast<int>(820 * main_scale),
                         SDL_WINDOW_RESIZABLE | SDL_WINDOW_HIGH_PIXEL_DENSITY);
    if (window == nullptr) {
        SDL_Log("SDL_CreateWindow: %s", SDL_GetError());
        return 1;
    }
    SDL_SetWindowPosition(window, SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED);

    // SDL_GPU rather than SDL_Renderer: the ImGui SDL_Renderer3 backend lists
    // multi-viewport as unsupported, and popping a panel into a real OS window needs
    // it. SDL_GPU is part of SDL3, so this costs no extra dependency.
    SDL_GPUDevice *const gpu = SDL_CreateGPUDevice(
        SDL_GPU_SHADERFORMAT_SPIRV | SDL_GPU_SHADERFORMAT_DXIL | SDL_GPU_SHADERFORMAT_MSL |
            SDL_GPU_SHADERFORMAT_METALLIB,
        false, nullptr);
    if (gpu == nullptr) {
        SDL_Log("SDL_CreateGPUDevice: %s", SDL_GetError());
        return 1;
    }
    if (!SDL_ClaimWindowForGPUDevice(gpu, window)) {
        SDL_Log("SDL_ClaimWindowForGPUDevice: %s", SDL_GetError());
        return 1;
    }
    SDL_SetGPUSwapchainParameters(gpu, window, SDL_GPU_SWAPCHAINCOMPOSITION_SDR,
                                  SDL_GPU_PRESENTMODE_VSYNC);

    IMGUI_CHECKVERSION();
    ImGui::CreateContext();
    ImGuiIO &io = ImGui::GetIO();
    io.IniFilename = nullptr; // don't litter an imgui.ini next to the concept
    io.ConfigFlags |= ImGuiConfigFlags_NavEnableKeyboard;
    io.ConfigFlags |= ImGuiConfigFlags_DockingEnable;

    // ── Viewports: X11 yes, Wayland no ───────────────────────────────────────
    // Multi-viewport is what lets a panel become a real OS window, and it works on
    // X11. On Wayland it does not hold up: the compositor owns window placement and
    // there is no protocol for a client to learn where its window went, so ImGui reads
    // a torn-off panel back as overlapping the host and auto-merge reclaims it. Measured
    // here, the platform-window count collapsed 4 -> 3 -> 2 -> 1 within a second of
    // launch — every popped-out panel silently snapped back.
    //
    // Rather than ship a feature that quietly undoes itself, viewports are simply off
    // under Wayland. Pop-out still works there, as a free-floating window inside the
    // player — movable and resizable, just not its own OS window.
    const char *video_driver = SDL_GetCurrentVideoDriver();
    const bool  is_wayland = video_driver != nullptr && SDL_strncmp(video_driver, "wayland", 7) == 0;
    if (!is_wayland)
        io.ConfigFlags |= ImGuiConfigFlags_ViewportsEnable;

    concept_apply_theme();
    ImGui::GetStyle().ScaleAllSizes(main_scale);
    ImGui::GetStyle().FontScaleDpi = main_scale;
    io.ConfigDpiScaleFonts         = true;
    io.ConfigDpiScaleViewports     = true;

    // Popped-out panels are separate OS windows; leaving WindowBg translucent there
    // would show the desktop through them.
    ImGui::GetStyle().Colors[ImGuiCol_WindowBg].w = 1.0f;

    ImGui_ImplSDL3_InitForSDLGPU(window);
    ImGui_ImplSDLGPU3_InitInfo init_info{};
    init_info.Device               = gpu;
    init_info.ColorTargetFormat    = SDL_GetGPUSwapchainTextureFormat(gpu, window);
    init_info.MSAASamples          = SDL_GPU_SAMPLECOUNT_1;
    init_info.SwapchainComposition = SDL_GPU_SWAPCHAINCOMPOSITION_SDR;
    init_info.PresentMode          = SDL_GPU_PRESENTMODE_VSYNC;
    ImGui_ImplSDLGPU3_Init(&init_info);

    SDL_Log("concept_player: SDL video driver = %s, OS-window pop-out = %s",
            video_driver != nullptr ? video_driver : "?",
            is_wayland ? "off (Wayland — panels pop out in-window instead)" : "on");

    ConceptPlayerApp app;
    concept_apply_args(argc, argv, app);
    bool done                 = false;
    bool window_is_fullscreen = false;
    // Viewports.Size counts the main viewport plus one entry per torn-off panel, so a
    // change here is the ground truth for "an OS window was actually created" —
    // independent of whether the compositor chose to show it where you expected.
    int  last_viewport_count  = -1;

    while (!done) {
        SDL_Event event;
        while (SDL_PollEvent(&event)) {
            ImGui_ImplSDL3_ProcessEvent(&event);
            if (event.type == SDL_EVENT_QUIT)
                done = true;
            if (event.type == SDL_EVENT_WINDOW_CLOSE_REQUESTED &&
                event.window.windowID == SDL_GetWindowID(window))
                done = true;
        }

        if ((SDL_GetWindowFlags(window) & SDL_WINDOW_MINIMIZED) != 0) {
            SDL_Delay(10);
            continue;
        }

        ImGui_ImplSDLGPU3_NewFrame();
        ImGui_ImplSDL3_NewFrame();
        ImGui::NewFrame();
        // ImAnim's mandatory per-frame pump, once, right after NewFrame(). Miss it and
        // every animated value freezes at frame 0 — which reads as "the animation does
        // nothing" rather than as a missing call.
        Motion::begin_frame();

        app.draw();

        if (app.quit_requested())
            done = true;

        // Apply the app's fullscreen intent to the OS window, only on change.
        if (app.fullscreen() != window_is_fullscreen) {
            window_is_fullscreen = app.fullscreen();
            SDL_SetWindowFullscreen(window, window_is_fullscreen);
        }

        ImGui::Render();
        ImDrawData *draw_data   = ImGui::GetDrawData();
        const bool  is_minimized = draw_data->DisplaySize.x <= 0.0f || draw_data->DisplaySize.y <= 0.0f;

        SDL_GPUCommandBuffer *cmd = SDL_AcquireGPUCommandBuffer(gpu);
        SDL_GPUTexture       *swapchain = nullptr;
        SDL_WaitAndAcquireGPUSwapchainTexture(cmd, window, &swapchain, nullptr, nullptr);

        if (swapchain != nullptr && !is_minimized) {
            // Mandatory for this backend: uploads the vertex/index buffers before the
            // render pass that consumes them.
            ImGui_ImplSDLGPU3_PrepareDrawData(draw_data, cmd);

            SDL_GPUColorTargetInfo target{};
            target.texture     = swapchain;
            target.clear_color = SDL_FColor{0.03f, 0.03f, 0.04f, 1.0f};
            target.load_op     = SDL_GPU_LOADOP_CLEAR;
            target.store_op    = SDL_GPU_STOREOP_STORE;

            SDL_GPURenderPass *pass = SDL_BeginGPURenderPass(cmd, &target, 1, nullptr);
            ImGui_ImplSDLGPU3_RenderDrawData(draw_data, cmd, pass);
            SDL_EndGPURenderPass(pass);
        }

        if ((io.ConfigFlags & ImGuiConfigFlags_ViewportsEnable) != 0) {
            ImGui::UpdatePlatformWindows();
            ImGui::RenderPlatformWindowsDefault();

            const int viewport_count = ImGui::GetPlatformIO().Viewports.Size;
            if (viewport_count != last_viewport_count) {
                last_viewport_count = viewport_count;
                SDL_Log("concept_player: platform windows = %d (1 main + %d popped out)",
                        viewport_count, viewport_count - 1);
            }
        }

        SDL_SubmitGPUCommandBuffer(cmd);
    }

    SDL_WaitForGPUIdle(gpu);
    ImGui_ImplSDL3_Shutdown();
    ImGui_ImplSDLGPU3_Shutdown();
    ImGui::DestroyContext();

    SDL_ReleaseWindowFromGPUDevice(gpu, window);
    SDL_DestroyGPUDevice(gpu);
    SDL_DestroyWindow(window);
    SDL_Quit();
    return 0;
}
