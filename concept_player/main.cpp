// Video-player design concept for my_imgui_sdl3_vulkan.
//
// A standalone program that prototypes the sketched player layout so the interaction
// can be judged before any of it is grafted onto the real player:
//
//   * menu bar across the top
//   * scene view down the left — a thumbnail every N seconds, click to jump
//   * folder view down the right — the clips next to this one, hover to preview
//   * hover preview floating over the video
//   * transport across the bottom — full-width seek strip above the controls
//
// Everything auto-hides, everything slides rather than cuts, and every panel can be
// popped out of the player into its OWN OS window (View > <panel> > options, or the
// [>] button in the panel header).
//
// There is NO decoder here. Frames are generated by FramePattern, which is the point:
// the questions this program answers are about reveal timing, motion, and layout, none
// of which need mpv. Every widget is written against plain data (a timestamp, a tile)
// so the port to real frames touches the draw call and nothing else.
//
// Built as part of the project; run it with:
//   ./build/debug/concept_player   (or: cmake --build build/all --target concept_player)
#include <SDL3/SDL.h>

#include "imgui.h"
#include "imgui_impl_sdl3.h"
#include "imgui_impl_sdlgpu3.h"

#include "concept_player_app.hpp"
#include "motion.hpp"

